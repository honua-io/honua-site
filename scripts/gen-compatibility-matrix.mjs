#!/usr/bin/env node
// Regenerate the public SDK availability table on client-compatibility.html
// from data/sdk-availability.v1.json. This file deliberately reports only
// externally verifiable package state; it must never manufacture future version
// windows from support fixtures or private policy data.
//
// Usage:  node scripts/gen-compatibility-matrix.mjs [--check]
//   (no args)  rewrite the generated region in place
//   --check    exit non-zero if the page is out of date (for CI)

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const policyPath = join(repoRoot, "data", "sdk-availability.v1.json");
const pagePath = join(repoRoot, "client-compatibility.html");

const START = "<!-- GENERATED:sdk-matrix START -->";
const END = "<!-- GENERATED:sdk-matrix END -->";

function esc(s) {
  return String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function render(policy) {
  const rows = policy.sdks.map((sdk) => {
    const version = sdk.publishedVersion
      ? `<code>${esc(sdk.publishedVersion)}</code>`
      : "Not published";
    const install = sdk.installCommand
      ? `<code>${esc(sdk.installCommand)}</code>`
      : `<a href="${esc(sdk.sourceUrl)}" target="_blank" rel="noopener noreferrer">Source preview ↗</a>`;
    return (
      `            <tr>` +
      `<td><strong>${esc(sdk.displayName)}</strong><br /><code>${esc(sdk.packageName)}</code></td>` +
      `<td><span class="evidence-badge ${sdk.publishedVersion ? "amber" : "blue"}">${esc(sdk.availability)}</span></td>` +
      `<td>${version}</td>` +
      `<td>${install}</td>` +
      `<td>${esc(sdk.compatibility)}</td>` +
      `</tr>`
    );
  });

  const companions = policy.sdks.flatMap((sdk) => sdk.companionPackages ?? []);
  const companionNote = companions.length
    ? `      <p class="note"><strong>JavaScript migration companions.</strong> ${companions
        .map(
          (pkg) =>
            `<code>${esc(pkg.packageName)}@${esc(pkg.publishedVersion)}</code> — ${esc(pkg.purpose)}`
        )
        .join("; ")}.</p>`
    : "";

  return [
    START,
    `      <!-- Generated by scripts/gen-compatibility-matrix.mjs from data/sdk-availability.v1.json`,
    `           schemaVersion=${policy.schemaVersion} checkedAt=${policy.checkedAt}. Do not edit by hand. -->`,
    `      <div class="table-wrap" tabindex="0" role="region" aria-label="Scrollable SDK availability table">`,
    `        <table>`,
    `          <caption class="sr-only">Current Honua SDK package availability and compatibility boundaries</caption>`,
    `          <thead>`,
    `            <tr><th scope="col">SDK</th><th scope="col">Availability</th><th scope="col">Published version</th><th scope="col">Install path</th><th scope="col">Compatibility boundary</th></tr>`,
    `          </thead>`,
    `          <tbody>`,
    ...rows,
    `          </tbody>`,
    `        </table>`,
    `      </div>`,
    companionNote,
    `      <p class="prov">Verified public package state from <a href="data/sdk-availability.v1.json"><code>sdk-availability.v1.json</code></a> — checked ${esc(policy.checkedAt)}.</p>`,
    `      ${END}`,
  ].join("\n");
}

const policy = JSON.parse(readFileSync(policyPath, "utf8"));
const page = readFileSync(pagePath, "utf8");

const startIdx = page.indexOf(START);
const endIdx = page.indexOf(END);
if (startIdx === -1 || endIdx === -1 || endIdx < startIdx) {
  console.error(
    `Could not find generated markers (${START} … ${END}) in ${pagePath}`
  );
  process.exit(2);
}

const before = page.slice(0, startIdx);
const after = page.slice(endIdx + END.length);
const next = before + render(policy) + after;

const check = process.argv.includes("--check");
if (check) {
  if (next !== page) {
    console.error(
      "client-compatibility.html is out of date with data/sdk-availability.v1.json.\n" +
        "Run: node scripts/gen-compatibility-matrix.mjs"
    );
    process.exit(1);
  }
  console.log("client-compatibility.html matrix is up to date.");
} else {
  writeFileSync(pagePath, next);
  console.log("Regenerated SDK matrix in client-compatibility.html");
}
