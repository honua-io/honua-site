#!/usr/bin/env node
// Regenerate the SDK client-compatibility matrix on client-compatibility.html
// from the synced policy snapshot data/compatibility-policy.v1.json.
//
// The canonical policy lives in honua-io/honua-support
// (compatibility/compatibility-policy.v1.json, honua-support#42); data/README.md
// documents how to resync the snapshot. This generator keeps the on-page table a
// derived view of that policy so the matrix cannot drift silently — any change to
// the policy shows up as a diff in the generated region.
//
// Usage:  node scripts/gen-compatibility-matrix.mjs [--check]
//   (no args)  rewrite the generated region in place
//   --check    exit non-zero if the page is out of date (for CI)

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const policyPath = join(repoRoot, "data", "compatibility-policy.v1.json");
const pagePath = join(repoRoot, "client-compatibility.html");

const START = "<!-- GENERATED:sdk-matrix START -->";
const END = "<!-- GENERATED:sdk-matrix END -->";

// KB references that have a published article on this site. Others render as
// plain policy ids until an article is promoted for them.
const KB_PAGES = {
  "KB-COMPAT-0001": "kb-compat-0001.html",
};

const AREA_LABELS = {
  "sdk-js": "sdk-js (@honua/sdk-js)",
  "sdk-dotnet": "sdk-dotnet (Honua.Sdk)",
  "sdk-python": "sdk-python (honua-sdk)",
};

function esc(s) {
  return String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

function kbCell(ref) {
  if (!ref) return "—";
  const page = KB_PAGES[ref];
  return page
    ? `<a href="${page}"><code>${esc(ref)}</code></a>`
    : `<code>${esc(ref)}</code>`;
}

function render(policy) {
  const rows = policy.products.map((p) => {
    const supported = (p.supported ?? [])
      .map((w) => `<code>${esc(w.sdkRange)}</code>`)
      .join("<br />");
    const server = (p.supported ?? [])
      .map((w) => `<code>${esc(w.serverRange)}</code>`)
      .join("<br />");
    const bad = (p.knownBad ?? [])
      .map(
        (w) =>
          `<code>${esc(w.sdkRange)}</code> <span class="kb-id">(${esc(w.id)})</span>`
      )
      .join("<br />");
    const kb = (p.knownBad ?? []).map((w) => kbCell(w.kbReference)).join("<br />");
    const label = AREA_LABELS[p.productArea] ?? p.productArea;
    return (
      `            <tr>` +
      `<td><strong>${esc(label)}</strong></td>` +
      `<td>${supported || "—"}</td>` +
      `<td>${server || "—"}</td>` +
      `<td>${bad || "—"}</td>` +
      `<td><strong>${esc(p.approvedTarget ?? "—")}</strong></td>` +
      `<td>${kb || "—"}</td>` +
      `</tr>`
    );
  });

  return [
    START,
    `      <!-- Generated by scripts/gen-compatibility-matrix.mjs from data/compatibility-policy.v1.json`,
    `           policyVersion=${policy.policyVersion} snapshot=${policy.generatedAt}. Do not edit by hand. -->`,
    `      <div class="table-wrap">`,
    `        <table>`,
    `          <thead>`,
    `            <tr><th>SDK</th><th>Supported SDK versions</th><th>Supported against server</th><th>Known-bad window</th><th>Policy-approved upgrade target</th><th>Guided fix</th></tr>`,
    `          </thead>`,
    `          <tbody>`,
    ...rows,
    `          </tbody>`,
    `        </table>`,
    `      </div>`,
    `      <p class="prov">Generated from <code>compatibility-policy.v1.json</code> — policy version ${esc(
      policy.policyVersion
    )}, snapshot ${esc(policy.generatedAt)}.</p>`,
    `      ${END}`,
  ].join("\n");
}

const policy = JSON.parse(readFileSync(policyPath, "utf8"));
const page = readFileSync(pagePath, "utf8");

const startIdx = page.indexOf(START);
const endIdx = page.indexOf(END);
if (startIdx === -1 || endIdx === -1 || endIdx < startIdx) {
  console.error(
    `Could not find generated markers (${START} … ${END}) in ${pagePath}`
  );
  process.exit(2);
}

const before = page.slice(0, startIdx);
const after = page.slice(endIdx + END.length);
const next = before + render(policy) + after;

const check = process.argv.includes("--check");
if (check) {
  if (next !== page) {
    console.error(
      "client-compatibility.html is out of date with data/compatibility-policy.v1.json.\n" +
        "Run: node scripts/gen-compatibility-matrix.mjs"
    );
    process.exit(1);
  }
  console.log("client-compatibility.html matrix is up to date.");
} else {
  writeFileSync(pagePath, next);
  console.log("Regenerated SDK matrix in client-compatibility.html");
}
