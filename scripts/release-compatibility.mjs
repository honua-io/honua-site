#!/usr/bin/env node
// Project the release repository's generated documentation; never derive a separate version policy.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const START = '<!-- GENERATED:release-compatibility START -->';
const END = '<!-- GENERATED:release-compatibility END -->';
const REPO = 'https://github.com/honua-io/honua-release';
const FILES = {
  table: ['docs/SDK-SERVER-COMPATIBILITY.md', 'data/release-compatibility.md'],
  lock: ['docs/platform-lock.v1.draft.yaml', 'data/release-compatibility-lock.yaml'],
};
const RECORD = 'data/release-compatibility-source.v1.json';
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const escape = text => String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');

export function validateRecord(record) {
  if (record.schemaVersion !== 1 || record.repository !== REPO || !/^[a-f0-9]{40}$/.test(record.revision)) throw new Error('Source must pin the release repository and immutable commit');
  for (const [key, [sourcePath, localPath]] of Object.entries(FILES)) {
    const file = record[key];
    if (!file || file.sourcePath !== sourcePath || file.localPath !== localPath || !/^[a-f0-9]{64}$/.test(file.sha256)) throw new Error(`Invalid ${key} source pin`);
  }
}

function inline(text, record) {
  return escape(text).replace(/`([^`]+)`/g, '<code>$1</code>').replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
    .replace('[Derivation rule](SDK-SERVER-BASELINE-RULE.md)', `<a href="${REPO}/blob/${record.revision}/docs/SDK-SERVER-BASELINE-RULE.md">Derivation rule</a>`);
}

export function render(markdown, record) {
  validateRecord(record);
  if (!markdown.startsWith('# SDK and server compatibility\n') || !markdown.includes('\n## UPGRADE EDGES\n')) throw new Error('Missing compatibility or upgrade section');
  const html = markdown.trim().split(/\n\s*\n/).map(block => {
    if (block.startsWith('<!-- Generated by tools/generate_compatibility_table.py;')) return '';
    if (block.startsWith('# ')) return `<h2>${inline(block.slice(2), record)}</h2>`;
    if (block.startsWith('## ')) return `<h3>${inline(block.slice(3), record)}</h3>`;
    if (block.startsWith('| ')) {
      const rows = block.split('\n').map(line => line.slice(1, -1).split(/(?<!\\)\|/).map(cell => cell.trim().replace(/\\\|/g, '|')));
      const [header, separator, ...body] = rows;
      if (!separator || !separator.every(cell => /^:?-+:?$/.test(cell)) || !body.length || rows.some(row => row.length !== header.length)) throw new Error('Malformed generated release table');
      const caption = header.includes('SDK / protocol') ? 'SDK minimum server requirements' : 'Upgrade and recovery boundaries';
      return `<div class="table-wrap" tabindex="0" role="region" aria-label="Scrollable release compatibility table"><table><caption class="sr-only">${caption}</caption><thead><tr>` +
        header.map(cell => `<th scope="col">${inline(cell, record)}</th>`).join('') + '</tr></thead><tbody>' +
        body.map(row => '<tr>' + row.map(cell => `<td>${inline(cell, record)}</td>`).join('') + '</tr>').join('') + '</tbody></table></div>';
    }
    return `<p>${inline(block.replace(/\n/g, ' '), record)}</p>`;
  }).filter(Boolean).join('\n      ');
  return `${START}\n      ${html}\n      <p class="prov">Imported from <a href="${REPO}/blob/${record.revision}/${record.table.sourcePath}">the release repository at ${record.revision.slice(0, 12)}</a>. Download the <a href="${record.table.localPath}">generated Markdown</a>, <a href="${record.lock.localPath}">source lock</a>, or <a href="${RECORD}">source pins</a>.</p>\n      ${END}`;
}

export function project(root = ROOT, check = false) {
  const record = JSON.parse(readFileSync(join(root, RECORD), 'utf8'));
  validateRecord(record);
  for (const key of Object.keys(FILES)) if (sha256(readFileSync(join(root, record[key].localPath))) !== record[key].sha256) throw new Error(`${key} bytes disagree with release source pin`);
  const fragment = render(readFileSync(join(root, record.table.localPath), 'utf8'), record);
  const path = join(root, 'client-compatibility.html');
  const page = readFileSync(path, 'utf8');
  const start = page.indexOf(START), end = page.indexOf(END);
  if (start < 0 || end < start || page.indexOf(START, start + START.length) >= 0 || page.indexOf(END, end + END.length) >= 0) throw new Error('Missing or duplicate release table markers');
  const next = page.slice(0, start) + fragment + page.slice(end + END.length);
  if (check && next !== page) throw new Error('Release compatibility table is stale; regenerate it');
  if (!check) writeFileSync(path, next);
}

export function importRelease(checkout, revision, root = ROOT) {
  if (!/^[a-f0-9]{40}$/.test(revision)) throw new Error('Import requires an immutable release commit');
  const record = { schemaVersion: 1, repository: REPO, revision }, contents = {};
  for (const [key, [sourcePath, localPath]] of Object.entries(FILES)) {
    const bytes = execFileSync('git', ['-C', checkout, 'show', `${revision}:${sourcePath}`]);
    record[key] = { sourcePath, localPath, sha256: sha256(bytes) };
    contents[key] = bytes;
  }
  render(contents.table.toString('utf8'), record);
  for (const key of Object.keys(FILES)) writeFileSync(join(root, record[key].localPath), contents[key]);
  writeFileSync(join(root, RECORD), JSON.stringify(record, null, 2) + '\n');
  project(root);
}

export async function verifyRemote(root = ROOT) {
  const record = JSON.parse(readFileSync(join(root, RECORD), 'utf8'));
  validateRecord(record);
  for (const key of Object.keys(FILES)) {
    const url = `https://raw.githubusercontent.com/honua-io/honua-release/${record.revision}/${record[key].sourcePath}`;
    let bytes;
    for (const delay of [10000, 30000, 60000, 120000, 0]) {
      try {
        const response = await fetch(url, { signal: AbortSignal.timeout(15000) });
        if (!response.ok) throw new Error(`${response.status !== 403 && response.status !== 429 && response.status < 500 ? 'Permanent ' : ''}HTTP ${response.status}`);
        bytes = Buffer.from(await response.arrayBuffer());
        break;
      } catch (error) {
        if (!delay || error.message.startsWith('Permanent')) throw new Error(`Cannot verify ${key} source: ${error.message}`);
        await new Promise(resolve => setTimeout(resolve, delay));
      }
    }
    if (sha256(bytes) !== record[key].sha256) throw new Error(`${key} remote source digest mismatch`);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const args = process.argv.slice(2);
    if (args[0] === '--import-from' && args.length === 3) importRelease(args[1], args[2]);
    else if (args.length === 1 && args[0] === '--verify-remote') { project(ROOT, true); await verifyRemote(); }
    else if (!args.length || (args.length === 1 && args[0] === '--check')) project(ROOT, args[0] === '--check');
    else throw new Error('Usage: release-compatibility.mjs [--check | --verify-remote | --import-from CHECKOUT COMMIT]');
    console.log('PASS: release compatibility source and page agree');
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
